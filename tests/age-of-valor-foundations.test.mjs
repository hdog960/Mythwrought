import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createCombatScheduler} from '../src/age-of-valor/scheduler.mjs';
import {createCombatAuthorization} from '../src/age-of-valor/authorization.mjs';
import {projectCombatStats} from '../src/age-of-valor/statistics.mjs';
function session2Cases(check,createScheduler,createAuthorization,project){
  const d={kind:'light',windupMs:100,activeMs:50,recoveryMs:200};
  let s=createScheduler();s.begin(d);s.advance(100);
  check(s.abortForLifecycle().snapshot.state==='idle','active lifecycle abort');
  check(s.advance(500).events.length===0,'no stale attack after abort');
  s.interrupt('stagger',100);s.advance(20);s.interrupt('stagger',10);
  check(s.snapshot().deadline===600+100,'stagger cannot shorten'); // clock 620, deadline 700
  check(!s.abortForLifecycle().ok&&s.snapshot().state==='stagger','lifecycle cannot clear stagger');
  s.advance(80);check(s.snapshot().state==='idle','stagger exact deadline');
  s.interrupt('incapacitated',80);s.advance(10);s.interrupt('incapacitated',90);
  check(s.snapshot().deadline===800,'incapacitated extended');
  check(!s.interrupt('stagger',500).ok,'lower priority cannot overwrite');
  s.interrupt('dead');check(!s.abortForLifecycle().ok&&s.snapshot().state==='dead','abort cannot revive');
  s=createScheduler();let c={worldEpoch:1,alive:true,playable:true,combatMode:true,creative:false,mounted:false,readOnly:false};
  let permission=true;const definitions={light:{windupMs:100,activeMs:50,recoveryMs:200},block:{},dodge:{durationMs:100}};
  const a=createAuthorization({scheduler:s,worldEpoch:1,definitions,readContext:()=>c,authorize:()=>permission});
  definitions.light.windupMs=1;
  check(!a.request('cast').ok,'undefined action');
  permission=false;check(!a.request('light').ok&&s.snapshot().clock===0,'denied permission');
  permission=true;check(a.request('light').ok&&s.snapshot().deadline===100,'trusted copied timing');
  check(!a.request('block').ok,'overlap rejected');
  c={...c,playable:false};check(!a.advance(1000).ok&&s.snapshot().state==='idle'&&s.snapshot().clock===0,'overlay aborts without advancing');
  c={...c,playable:true};check(a.advance(100).events.length===0,'no delayed attack on resume');
  check(a.request('block').ok,'block authorized');let id=s.snapshot().actionId;
  check(!a.releaseBlock(id-1).ok,'stale block release');
  check(a.cancelInput().ok&&!a.releaseBlock(id).ok,'cancel prevents delayed release');
  c={...c,creative:true};check(!a.request('light').ok,'creative denies combat');
  c={...c,creative:false,mounted:true};check(!a.request('light').ok,'mount denied');
  c={...c,mounted:false,readOnly:true};check(!a.request('light').ok,'read only denied');
  c={...c,readOnly:false,combatMode:false};check(!a.request('light').ok,'exploration denied');
  c={...c,combatMode:true,alive:false};check(!a.advance(20).ok&&s.snapshot().state==='dead','authority death');
  c={...c,alive:true};check(!a.request('light').ok,'no automatic revival');
  check(a.acknowledgeRespawn().ok&&a.request('dodge').ok,'explicit authority revival');
  c={...c,worldEpoch:2};check(!a.advance(100).ok&&a.status().retired,'world retirement');
  c={...c,worldEpoch:1};check(!a.request('light').ok,'retired world cannot reopen');
  const base={maxHealth:100,maxStamina:100,maxMana:80,physicalAttack:8,magicalAttack:4,accuracy:1,criticalChance:.05,criticalDamage:1.5,mitigation:0,healthRegen:0,staminaRegen:5,manaRegen:2,actionEfficiency:1};
  for(const f of ['slashing','piercing','crushing','fire','frost','lightning','poison','arcane','resonance'])base['resistance.'+f]=0;
  const health={current:71,max:100},resources={stamina:40,mana:30};
  const options={base,health,resources,layers:{skill:[{id:'strength:1',stat:'physicalAttack',delta:3},{id:'vitality:1',stat:'maxHealth',delta:20}],equipment:[{id:'fixture',stat:'mitigation',delta:.2}],temporary:[{id:'burn',stat:'resistance.fire',delta:-.25}]}};
  const p=project(options);
  check(p.stats.physicalAttack===11&&p.stats.magicalAttack===4,'skill math');
  check(p.health.current===71&&p.stats.maxHealth===100&&p.requestedHealthMax===120&&p.healthMaxRequiresAuthority,'no duplicate health ownership');
  check(p.stats.mitigation===.2&&p.resistance.fire===-.25,'equipment and effect layers');
  check(p.resources.stamina===40&&p.resources.mana===30,'resources read only');
  check(Object.isFrozen(p)&&Object.isFrozen(p.stats)&&Object.isFrozen(p.health)&&Object.isFrozen(p.resistance),'immutable projection');
  health.current=50;check(p.health.current===71&&project(options).health.current===50,'live authority snapshot no mutation');
  const capped=project({...options,layers:{skill:[{id:'fixture',stat:'criticalChance',delta:2},{id:'fixture2',stat:'mitigation',delta:10}]}});
  check(capped.stats.criticalChance===1&&capped.stats.mitigation===.95&&capped.limited.length===2,'numerical caps');
  const reject=(o)=>{try{project(o);return false;}catch{return true;}};
  check(reject({...options,health:{current:101,max:100}}),'invalid health rejected');
  check(reject({...options,resources:{stamina:-1,mana:30}}),'invalid stamina rejected');
  check(reject({...options,base:{...base,physicalAttack:NaN}}),'invalid base rejected');
  check(reject({...options,layers:{skill:[{id:'x',stat:'__proto__',delta:1}]}}),'unknown stat rejected');
  check(reject({...options,layers:{skill:[{id:'x',stat:'physicalAttack',delta:1},{id:'x',stat:'physicalAttack',delta:2}]}}),'duplicate layer ID rejected');
  check(reject({...options,layers:{skill:[{id:'x',stat:'physicalAttack',delta:Infinity}]}}),'nonfinite modifier rejected');
  check(reject({...options,layers:{unknown:[]}}),'unknown layer rejected');
}
test('AV1 authorization and AV2 projection',()=>session2Cases((ok,name)=>assert.ok(ok,name),createCombatScheduler,createCombatAuthorization,projectCombatStats));
