import assert from 'node:assert/strict';
import {inspectBodyFit,canPlaceWithoutTrapping} from '../src/voxel-shape-fit.mjs';
import {FULL_CUBE,rotateShape} from '../src/voxel-shape-interactions.mjs';
const slab={boxes:[[0,0,0,1,.5,1]]};
const post={boxes:[[0,0,0,.25,1,.25]]};
const at=(x,y,z)=>x===2&&y===0&&z===0?slab:null;
assert.equal(inspectBodyFit([2,.5,0,3,1.5,1],at).fits,true,'touching top is not penetrating');
assert.equal(inspectBodyFit([2,.49,0,3,1.5,1],at).fits,false,'overlapping slab blocks player');
assert.equal(inspectBodyFit([2.5,0,.5,2.75,1,.75],(x,y,z)=>x===2&&y===0&&z===0?post:null).fits,true,'narrow post leaves room');
assert.equal(inspectBodyFit([2.1,0,.1,2.4,1,.4],(x,y,z)=>x===2&&y===0&&z===0?post:null).fits,false);
assert.equal(inspectBodyFit([-1,0,-1,0,1,0],(x,y,z)=>x===-1&&y===0&&z===-1?FULL_CUBE:null).fits,false,'negative cells');
assert.equal(inspectBodyFit([1,0,0,2,1,1],(x,y,z)=>x===2?FULL_CUBE:null).fits,true,'adjacent cube contact');
assert.equal(inspectBodyFit([1.99,0,0,2.01,1,1],(x,y,z)=>x===2?FULL_CUBE:null).fits,false,'cross-cell penetration');
assert.equal(canPlaceWithoutTrapping(slab,[2,0,0],()=>null,[2,.5,0,3,1.5,1]),true);
assert.equal(canPlaceWithoutTrapping(slab,[2,0,0],()=>null,[2,.2,0,3,1.2,1]),false);
assert.equal(canPlaceWithoutTrapping(rotateShape(post,1),[0,0,0],()=>null,[.8,0,.8,.95,1,.95]),true);
assert.throws(()=>inspectBodyFit([0,0,0,100,100,100],()=>null),RangeError);
assert.throws(()=>inspectBodyFit([0,0,0,1,1,1],()=>({boxes:[[0,0,0,2,1,1]]})),TypeError);
assert.throws(()=>inspectBodyFit([0,0,0,0,1,1],()=>null),TypeError);
console.log('shape-aware player fit: 13 assertions passed');
