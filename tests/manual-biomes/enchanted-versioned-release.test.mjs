// Only new generator identity / real persistence / renderer-capability delta.
import test from 'node:test';
import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {FourRegionWorld,fourRegionProfile,M7_ENVIRONMENT_GENERATOR,ENCHANTED_P2_GENERATOR,isEnvironmentGenerator} from '../../src/manual-biomes/profile-world.mjs';
import {M2_WORLD_MODE,planM2WorldChoice,openM2World,saveM2World,exportM2World,inspectM2WorldExport} from '../../src/manual-biomes/m2-runtime-bridge.mjs';
import {readFourRegionProfile,BIOME_PROFILE_SUFFIX} from '../../src/manual-biomes/profile-storage.mjs';
import {worldSlotKey} from '../../src/seeds.mjs';
import {BLOCK,meshChunk} from '../../src/voxel.mjs';
import {planEnvironmentalScenery} from '../../src/nonblock/staged-habitats.mjs';
import {hasValidatedV6SkyProfile,resolveV6SkyBiome} from '../../src/sky-v6-adapter.mjs';
const previous=await import(pathToFileURL(resolve(process.env.ENCHANTED_PREVIOUS_ROOT,'src/manual-biomes/m2-runtime-bridge.mjs')).href);
const seed=179;
const memory=()=>{
 const entries=new Map();
 return {get length(){return entries.size;},key:i=>[...entries.keys()][i]??null,
  getItem:k=>entries.get(k)??null,setItem:(k,v)=>entries.set(k,String(v)),removeItem:k=>entries.delete(k),
  snapshot:()=>[...entries].sort((a,b)=>a[0].localeCompare(b[0]))};
};
const choice=(id,mode=M2_WORLD_MODE.OPEN)=>planM2WorldChoice(String(id),mode,{confirmed:mode!==M2_WORLD_MODE.OPEN});
const create=(s,id,mode)=>openM2World(s,choice(id,mode));
const key=worldSlotKey(seed);
test('explicit new version alone enables durable forest, preserves default M7 and refuses existing/claimed seeds',()=>{
 const s=memory();
 const old=create(s,7,M2_WORLD_MODE.CREATE_ENVIRONMENT_V7);
 assert.equal(saveM2World(s,old.world).ok,true);
 const prior=s.snapshot().filter(([k])=>k.startsWith(worldSlotKey(7)));
 assert.equal(old.base.enchantedTreesEnabled,false);
 assert.throws(()=>planM2WorldChoice(String(seed),M2_WORLD_MODE.CREATE_ENCHANTED_P2),/explicit creator confirmation/);
 assert.throws(()=>create(s,7,M2_WORLD_MODE.CREATE_ENCHANTED_P2),/existing profile/i);
 assert.deepEqual(s.snapshot().filter(([k])=>k.startsWith(worldSlotKey(7))),prior);
 s.setItem('mythwrought-exploration-v1-2026','claimed');
 assert.throws(()=>create(s,2026,M2_WORLD_MODE.CREATE_ENCHANTED_P2),/Existing seed\/save prevents activation/);
 const newWorld=create(s,seed,M2_WORLD_MODE.CREATE_ENCHANTED_P2);
 assert.equal(newWorld.base.generationProfile.generator,ENCHANTED_P2_GENERATOR);
 assert.equal(newWorld.base.experimentalEnchantedTrees,false);
 assert.equal(newWorld.base.enchantedTreesEnabled,true);
 assert.equal(saveM2World(s,newWorld.world).ok,true);
 assert.equal(readFourRegionProfile(s,seed).profile.generator,ENCHANTED_P2_GENERATOR);
 assert.deepEqual(s.snapshot().filter(([k])=>k.startsWith(worldSlotKey(7))),prior);
 const snapshot=s.snapshot();
 assert.throws(()=>previous.openM2World(s,previous.planM2WorldChoice(String(seed))),/Damaged biome profile/);
 assert.deepEqual(s.snapshot(),snapshot,'older release refuses new profile without rewriting bytes');
 assert.throws(()=>fourRegionProfile(seed,ENCHANTED_P2_GENERATOR+'-unknown'),/Unknown biome generator/);
 assert.throws(()=>new FourRegionWorld(seed,fourRegionProfile(seed,ENCHANTED_P2_GENERATOR),{experimentalEnchantedTrees:true}),/explicit M7 opt-in/);
 assert.throws(()=>new FourRegionWorld(seed,fourRegionProfile(seed,M7_ENVIRONMENT_GENERATOR),{experimentalEnchantedTrees:true}).save(),/cannot be saved as historical M7/);
 console.log('ENCHANTED VERSION IDENTITY '+JSON.stringify({newGenerator:ENCHANTED_P2_GENERATOR,oldGenerator:old.base.generationProfile.generator,oldBytesUnchanged:true,olderLoaderRefused:true}));
});
test('real newly versioned tree voxel edits persist through profile save, cold open and verified portable import',()=>{
 const s=memory(),n=create(s,seed,M2_WORLD_MODE.CREATE_ENCHANTED_P2),w=n.world;
 const historical=new FourRegionWorld(seed,fourRegionProfile(seed,M7_ENVIRONMENT_GENERATOR));
 n.base._environmentTreeAt(-48,19,-528);
 const entries=n.base._environmentTreeChunks.get('-3,-33');
 const witness=[...entries].find(([k,id])=>{const p=k.split(',').map(Number);return n.base.get(...p)===id&&historical.get(...p)!==id});
 assert.ok(witness,'real changed natural tree cell must exist');
 const [k,id]=witness,p=k.split(',').map(Number);
 assert.equal(w.get(...p),id);
 assert.equal(w.set(...p,BLOCK.AIR),true);
 assert.equal(w.get(...p),BLOCK.AIR);
 assert.equal(saveM2World(s,w).ok,true);
 const raw=s.getItem(key),profile=s.getItem(key+BIOME_PROFILE_SUFFIX);
 const cold=create(s,seed,M2_WORLD_MODE.OPEN);
 assert.equal(cold.base.generationProfile.generator,ENCHANTED_P2_GENERATOR);
 assert.equal(cold.world.get(...p),BLOCK.AIR);
 assert.equal(cold.base.naturalAndLandmarkBlock(...p),id);
 assert.deepEqual(cold.world.save(),w.save());
 const exported=exportM2World(cold.world),inspected=inspectM2WorldExport(exported),importStorage=memory();
 assert.equal(inspected.world.base.generationProfile.generator,ENCHANTED_P2_GENERATOR);
 openM2World(importStorage,planM2WorldChoice(String(seed),M2_WORLD_MODE.IMPORT_PROFILE,{confirmed:true,generator:ENCHANTED_P2_GENERATOR}));
 assert.equal(saveM2World(importStorage,inspected.world).ok,true);
 assert.equal(exportM2World(create(importStorage,seed,M2_WORLD_MODE.OPEN).world),exported);
 const wrong=JSON.parse(exported);wrong.profile.generator='unknown-generator';
 assert.throws(()=>inspectM2WorldExport(JSON.stringify(wrong)),/Unsupported or mismatched/);
 assert.equal(s.getItem(key),raw);assert.equal(s.getItem(key+BIOME_PROFILE_SUFFIX),profile);
 assert.equal(JSON.parse(raw).schema,1);
 console.log('ENCHANTED VERSION SAVE ROUNDTRIP '+JSON.stringify({witness:p,natural:id,edits:JSON.parse(raw).edits,exportImportExact:true,profileIdentity:ENCHANTED_P2_GENERATOR}));
});
test('new generator uses real environmental terrain, nonblock scenery and V6 sky capability without aliasing M7',()=>{
 const s=memory(),n=create(s,seed,M2_WORLD_MODE.CREATE_ENCHANTED_P2);
 const w=n.world,b=n.base;
 assert.equal(isEnvironmentGenerator(ENCHANTED_P2_GENERATOR),true);
 assert.equal(isEnvironmentGenerator(M7_ENVIRONMENT_GENERATOR),true);
 assert.equal(isEnvironmentGenerator(ENCHANTED_P2_GENERATOR+'-unknown'),false);
 const mesh=meshChunk(w,-3,-33);
 assert.ok(mesh instanceof Float32Array&&mesh.length>0&&mesh.every(Number.isFinite));
 const scene=planEnvironmentalScenery(b,-3,-33);
 assert.ok(scene.length>0);
 assert.equal(hasValidatedV6SkyProfile(w),true);
 const sky=resolveV6SkyBiome(w,-40,-520);
 assert.equal(sky?.name,'enchanted');assert.equal(sky.generator,ENCHANTED_P2_GENERATOR);
 console.log('ENCHANTED VERSION RENDER COMPAT '+JSON.stringify({meshBytes:mesh.byteLength,sceneRequests:scene.length,sky:sky.name,generator:sky.generator}));
});
