import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createActionController} from '../src/age-of-valor/controller.mjs';
import {createGuardResolver} from '../src/age-of-valor/guard.mjs';
import {createDodgeCommand} from '../src/age-of-valor/dodge.mjs';
import {verifyCommittedDamage} from '../src/age-of-valor/committed-outcome.mjs';
import {createCombatScheduler} from '../src/age-of-valor/scheduler.mjs';
import {createResourceLedger} from '../src/age-of-valor/resources.mjs';
function cases(check,controller,guard,dodge,verify,makeScheduler,makeLedger){
 const reject=f=>{try{f();return false}catch{return true}};
 const opts={maximum:{stamina:10000,mana:10000},initial:{stamina:6000,mana:4000},regeneration:{combat:{stamina:0,mana:0},exploration:{stamina:0,mana:0}},delayMs:{stamina:0,mana:0}};
 let context={worldEpoch:1,alive:true,playable:true,combatMode:true,creative:false,mounted:false,readOnly:false};
 let authorized=true;
 const c=controller({makeScheduler,makeLedger,resourceOptions:opts,definitions:{light:{windupMs:10,activeMs:10,recoveryMs:10,cost:{stamina:7000,mana:0}},block:{cost:{stamina:1000,mana:100}},parry:{durationMs:100,cost:{stamina:1000,mana:0}},dodge:{durationMs:50,cost:{stamina:1000,mana:0}}},readContext:()=>context,authorize:()=>authorized,worldEpoch:1});
 check(!c.request('light').ok&&c.state().scheduler.state==='idle'&&c.state().resources.stamina===6000,'no action or debit when insufficient');
 authorized=false;check(!c.request('block').ok&&c.state().resources.stamina===6000,'authorization denied');
 authorized=true;const b=c.request('block');check(b.ok&&b.state.resources.stamina===5000&&b.state.resources.mana===3900,'atomic admission');
 check(!c.request('dodge').ok&&c.state().resources.stamina===5000,'busy no cost');
 const bid=b.state.scheduler.actionId;
 let startedAt=0;
 const guardPolicy={minimumDot:.5,parryWindowMs:40,blockBase:100,costPerDamage:100,parryCost:200,breakMs:80,blockReduction:.6};
 const g=guard({worldEpoch:1,policy:guardPolicy,readState:()=>({...c.state().scheduler,worldEpoch:1,active:true,forward:[1,0],startedAt}),charge:c.guardCharge});
 const hit=(sequence,extra={})=>({worldEpoch:1,sequence,at:c.state().scheduler.clock,amount:10,blockable:true,parryable:true,towardAttacker:[1,0],...extra});
 check(g.evaluate(hit(1,{towardAttacker:[-1,0]})).guard==='none'&&c.state().resources.stamina===5000,'rear hit not blocked');
 check(g.evaluate(hit(2)).guard==='block'&&c.state().resources.stamina===3900,'front block cost');
 check(g.evaluate(hit(2)).guard==='none'&&c.state().resources.stamina===3900,'duplicate impact denied');
 check(g.evaluate(hit(3,{blockable:false})).guard==='none','unblockable');
 check(g.evaluate(hit(4,{amount:100})).reason==='guard-broken'&&c.state().scheduler.state==='stagger','guard break');
 check(!c.releaseBlock(bid).ok&&!c.request('parry').ok,'break recovery cannot bypass');
 c.advance(79);check(c.state().scheduler.state==='stagger','recovery not early');
 c.advance(1);check(c.state().scheduler.state==='idle','recovery boundary');
 startedAt=c.state().scheduler.clock;
 check(c.request('parry').ok,'parry admitted');
 check(g.evaluate(hit(5)).guard==='parry','early parry');
 c.advance(40);check(g.evaluate(hit(6)).guard==='none','exact parry window ends');
 c.advance(60);check(c.state().scheduler.state==='idle','parry recovery complete');
 check(c.request('dodge').ok,'dodge admitted');
 context={...context,playable:false};check(!c.advance(50).ok&&c.state().scheduler.state==='idle','lifecycle abort');
 check(c.state().scheduler.clock===c.state().resources.clock,'clock agreement');
 context={...context,playable:true,worldEpoch:2};check(!c.request('block').ok&&c.state().retired,'old world retired');
 const identity={worldId:'world:1',profileId:'profile:1',actionId:'action:1',sourceId:'player:1'};
 let auth={...identity,active:true,state:'dodging',fixture:false},calls=0;
 const make=move=>dodge({identity,readAuthority:()=>auth,move,maxDistance:2,durationMs:50});
 const d=make(q=>{calls++;return {...q,accepted:true,blocked:true,collisionVerified:true,displacement:[.5,0]}});
 check(d.execute([0,0]).status==='invalid-direction','zero direction');
 check(d.execute([1,0]).distance===.5,'collision clipped displacement');
 check(d.execute([1,0]).status==='already-used'&&calls===1,'no replay');
 check(make(q=>({...q,accepted:true,blocked:false,collisionVerified:false,displacement:[1,0]})).execute([1,0]).status==='authority-uncertain','unverified collision');
 check(make(q=>({...q,accepted:true,blocked:false,collisionVerified:true,displacement:[3,0]})).execute([1,0]).status==='authority-uncertain','overreach');
 check(make(q=>({...q,accepted:true,blocked:false,collisionVerified:true,displacement:[-1,0]})).execute([1,0]).status==='authority-uncertain','backward receipt');
 auth={...auth,worldId:'world:2'};check(make(()=>{throw Error('not called')}).execute([1,0]).status==='not-authorized','wrong world');
 const req={...identity,transactionId:'tx:1',targetId:'mob:1',definitionId:'fixture:hit',fixture:true,amount:5};
 const v={request:req,definition:{id:'fixture:hit',scope:'fixture'},lookupCommitted:()=>({committed:true,requestAmount:5,receipt:{accepted:true,progressionCandidate:false}}),validateReceipt:(q,a)=>a};
 check(verify(v).outcome.progressionCandidate===false,'fixture provenance');
 check(reject(()=>verify({...v,request:{...req,fixture:false}})),'forged fixture flag');
 check(reject(()=>verify({...v,lookupCommitted:()=>null})),'missing commit');
 check(reject(()=>verify({...v,lookupCommitted:()=>({committed:true,requestAmount:6})})),'wrong amount');
}
test('AV7 guard, AV8 dodge and atomic admission',()=>cases((ok,name)=>assert.ok(ok,name),createActionController,createGuardResolver,createDodgeCommand,verifyCommittedDamage,createCombatScheduler,createResourceLedger));
