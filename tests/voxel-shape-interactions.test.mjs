import assert from 'node:assert/strict';
import {validateShape,FULL_CUBE,rotateShape,raycastShapes,canPlaceShape} from '../src/voxel-shape-interactions.mjs';
const half={boxes:[[0,0,0,1,.5,1]]};
const post={boxes:[[.375,0,.375,.625,1,.625]]};
assert.equal(validateShape(half),true);
assert.equal(validateShape({boxes:[[0,0,0,1,2,1]]}),false);
assert.deepEqual(rotateShape({boxes:[[0,0,0,.25,1,.5]]},1).boxes,[[.5,0,0,1,1,.25]]);
const at=(x,y,z)=>x===2&&y===0&&z===0?half:null;
assert.equal(raycastShapes([0,.75,.5],[1,0,0],at,5),null,'ray above slab must pass through');
const side=raycastShapes([0,.25,.5],[1,0,0],at,5);
assert.deepEqual(side.cell,[2,0,0]);
assert.equal(side.distance,2);
assert.deepEqual(side.normal,[-1,0,0]);
const top=raycastShapes([2.5,2,.5],[0,-1,0],at,5);
assert.equal(top.distance,1.5);
assert.deepEqual(top.normal,[0,1,0]);
const legacy=raycastShapes([0,.75,.5],[1,0,0],(x,y,z)=>x===2&&y===0&&z===0?FULL_CUBE:null,5);
assert.equal(legacy.distance,2);
assert.equal(raycastShapes([0,0,0],[1,0,0],()=>null,5),null);
const inside=raycastShapes([2.5,.25,.5],[1,0,0],at,5);
assert.equal(inside.distance,0);
assert.equal(canPlaceShape(half,[0,0,0],()=>null),true);
assert.equal(canPlaceShape(half,[0,0,0],()=>post),false);
assert.equal(canPlaceShape({boxes:[[0,.5,0,1,1,1]]},[0,0,0],()=>half),true);
assert.throws(()=>raycastShapes([0,0,0],[0,0,0],()=>null),RangeError);
assert.throws(()=>raycastShapes([0,0,0],[1,0,0],()=>({boxes:[[0,0,0,2,1,1]]})),TypeError);
console.log('voxel shape targeting: 16 assertions passed');
