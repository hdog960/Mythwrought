import {test} from 'node:test';
import assert from 'node:assert/strict';
import {scanMelee,createMeleeExecution} from '../src/age-of-valor/melee.mjs';
import {createResourceLedger} from '../src/age-of-valor/resources.mjs';
import {createCombatRegistry} from '../src/age-of-valor/registry.mjs';
function cases(check,scan,execution,ledger,delivery){
 const reject=f=>{try{f();return false}catch{return true}};
 const def=Object.freeze({id:'fixture:unarmed',scope:'fixture',type:'unarmed',delivery:'melee',reach:2,damage:[{}],geometry:Object.freeze({shape:'sweep',radius:.1,maxTargets:2})});
 const pose=(at,eye=[0,1,0],forward=[1,0,0])=>({at,eye,forward});
 const target=(id,p,q=p,extra={})=>({id,from:p,to:q,radius:.3,alive:true,attackable:true,friendly:false,resident:true,...extra});
 const front=target('mob:1',[1,1,0]),behind=target('mob:2',[-1,1,0]),far=target('mob:3',[4,1,0]),friendly=target('mob:4',[1,1,0],undefined,{friendly:true});
 const frame={definition:def,sourceId:'player:1',from:pose(0),to:pose(50),targets:[front,behind,far,friendly],lineOfSight:()=>true};
 check(scan(frame).map(x=>x.targetId).join()==='mob:1','direction reach friendly');
 check(scan({...frame,lineOfSight:()=>false}).length===0,'wall blocks');
 check(scan({...frame,lineOfSight:()=>{throw Error('unavailable')}}).length===0,'missing LOS fail closed');
 check(scan({...frame,targets:[target('mob:5',[1,1,-1],[1,1,1])]}).length===1,'moving target swept crossing');
 check(scan({...frame,targets:[target('mob:5',[1,1,0],undefined,{resident:false})]}).length===0,'unresident');
 check(scan({...frame,targets:[target('mob:5',[1,1,0],undefined,{alive:false})]}).length===0,'dead');
 check(scan({...frame,targets:[target('player:1',[1,1,0])]}).length===0,'self');
 check(reject(()=>scan({...frame,targets:[front,front]})),'duplicate snapshots');
 check(reject(()=>scan({...frame,to:pose(101)})),'oversized interval');
 check(reject(()=>scan({...frame,to:pose(50,[3,1,0])})),'teleport denied');
 check(reject(()=>scan({...frame,from:pose(0,[0,258,0])})),'height bound');
 check(scan({...frame,targets:[target('mob:b',[1,1,0]),target('mob:a',[1,1,0])]}).map(x=>x.targetId).join()==='mob:a,mob:b','stable tie order');
 check(scan({...frame,targets:[target('mob:5',[1,1,0],[1,1,3])]}).length===0,'discontinuous target ignored');
 const identity={worldId:'world:1',profileId:'profile:1',actionId:'action:1',sourceId:'player:1'};
 let authority={...identity,definitionId:def.id,active:true,fixture:true},writes=0;
 const make=(apply)=>execution({definition:def,identity,activeFrom:0,activeUntil:100,readAuthority:()=>authority,resolve:()=>({definitionId:def.id,amount:5}),apply,validateReceipt:(q,a)=>{if(a.transactionId!==q.transactionId||!a.accepted)throw Error('bad receipt');return a}});
 const e=make(q=>{writes++;return {...q,accepted:true}});
 check(e.step(frame).length===1&&writes===1,'authority call');
 check(e.step({...frame,from:pose(50),to:pose(100),targets:[front,target('mob:6',[1,1,0]),target('mob:7',[1,1,0])]}).length===1&&writes===2,'one hit per target and cap');
 check(e.status().closed&&e.step(frame).length===0,'expired action closed');
 const f=make(()=>{writes++;throw Error('uncertain')});
 check(f.step(frame)[0].status==='authority-uncertain'&&f.status().closed,'unknown write terminal');
 check(f.step(frame).length===0,'no retry unknown');
 const g=make(()=>{throw Error('must not call')});authority={...authority,worldId:'world:2'};
 check(g.step(frame).length===0&&g.status().closed,'world mismatch');
 authority={...identity,definitionId:def.id,active:true,fixture:false};const j=make(()=>{throw Error('must not call')});
 check(j.step(frame).length===0&&j.status().closed,'fixture provenance mismatch');
 check(reject(()=>delivery({...def,delivery:'projectile'})),'invalid unarmed delivery');
 check(reject(()=>delivery({...def,geometry:{shape:'self',radius:0,maxTargets:1}})),'incompatible shape');
 check(reject(()=>delivery({...def,reach:20})),'oversized melee');
 check(reject(()=>delivery({...def,geometry:{shape:'ray',radius:1,maxTargets:1}})),'ray radius');
 check(!reject(()=>delivery(def)),'valid sweep');
 const opts={maximum:{stamina:10000,mana:10000},initial:{stamina:6000,mana:4000},regeneration:{combat:{stamina:1001,mana:500},exploration:{stamina:2000,mana:1000}},delayMs:{stamina:500,mana:1000}};
 const l=ledger(opts);
 check(l.consume({sequence:1,cost:{stamina:2000,mana:1000},expectedRevision:0}).ok,'atomic debit');
 check(l.snapshot().stamina===4000&&l.snapshot().mana===3000,'both charged');
 check(!l.consume({sequence:1,cost:{stamina:1,mana:1},expectedRevision:1}).ok,'duplicate charge');
 check(!l.consume({sequence:2,cost:{stamina:5000,mana:1},expectedRevision:1}).ok&&l.snapshot().mana===3000,'insufficient no partial debit');
 check(!l.consume({sequence:2,cost:{stamina:1,mana:1},expectedRevision:2}).ok,'denied sequence retired');
 check(!l.consume({sequence:3,cost:{stamina:1,mana:1},expectedRevision:0}).ok,'stale revision');
 check(l.advance(400,'combat').snapshot.stamina===4000,'regen delay');
 check(l.advance(600,'combat').snapshot.stamina===4500&&l.snapshot().mana===3000,'delay split');
 check(l.advance(1000,'paused').snapshot.clock===1000,'pause no clock');
 check(l.advance(1000,'exploration').snapshot.mana===4000,'exploration regen');
 check(l.advance(60000,'exploration').snapshot.stamina===10000&&l.snapshot().mana===10000,'cap');
 check(!l.consume({sequence:4,cost:{stamina:-1,mana:0},expectedRevision:l.snapshot().revision}).ok,'negative cost');
 const a=ledger(opts),b=ledger(opts);a.advance(1000,'combat');for(let i=0;i<10;i++)b.advance(100,'combat');
 check(a.snapshot().stamina===b.snapshot().stamina&&a.snapshot().mana===b.snapshot().mana,'partition invariant');
 l.close();check(!l.advance(100,'combat').ok&&!l.consume({sequence:4,cost:{stamina:0,mana:0},expectedRevision:l.snapshot().revision}).ok,'closed ledger');
}
function validateDeliveryThroughRegistry(d){createCombatRegistry([{...d,version:1,requirements:[],power:'physical',damage:[{family:'crushing',amount:1,scaling:0}],timing:{windupMs:1,activeMs:1,recoveryMs:1,cooldownMs:0},cost:{stamina:0,mana:0},critical:false,effects:[],hooks:{animation:null,feedback:null}}]);}
test('AV5 melee and AV6 resources',()=>cases((ok,name)=>assert.ok(ok,name),scanMelee,createMeleeExecution,createResourceLedger,validateDeliveryThroughRegistry));
