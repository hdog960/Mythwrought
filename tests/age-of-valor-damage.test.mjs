import {test} from 'node:test';
import assert from 'node:assert/strict';
import {FAMILIES,createCombatRegistry} from '../src/age-of-valor/registry.mjs';
import {resolveDamage,validateDamageReceipt} from '../src/age-of-valor/damage.mjs';
function cases(check,registry,resolve,receipt,families){
 const d={id:'fixture:unarmed',version:1,scope:'fixture',type:'unarmed',requirements:[],delivery:'melee',damage:[{family:'fire',amount:10,scaling:0},{family:'crushing',amount:20,scaling:1}],power:'physical',reach:2.6,timing:{windupMs:100,activeMs:50,recoveryMs:200,cooldownMs:0},cost:{stamina:5,mana:0},critical:true,geometry:{shape:'sweep',radius:.6,maxTargets:1},effects:[],hooks:{animation:null,feedback:null}};
 const equipment={id:'fixture:weapon',version:1,scope:'fixture',type:'weapon',requirements:[{skillId:'skill:strength',level:5}],slot:'main-hand',actions:[d.id],modifiers:[{id:'fixture:bonus',stat:'physicalAttack',delta:3}],weight:2};
 const reject=(fn)=>{try{fn();return false}catch{return true}};
 const reg=registry([equipment,d],families);const def=reg.get(d.id);
 check(reg.size===2&&reg.get('missing:action')===null,'lookup');
 check(reg.list()[0].id===d.id,'stable sorted IDs');
 check(def.damage[0].family==='crushing','canonical family order');
 check(Object.isFrozen(def.damage)&&Object.isFrozen(def.damage[0])&&Object.isFrozen(def.timing),'deep immutable');
 d.damage[0].amount=100;check(def.damage[1].amount===10,'input copy');
 check(reject(()=>registry([d,d],families)),'duplicate id');
 check(reject(()=>registry([{...d,id:'bad'}],families)),'invalid id');
 check(reject(()=>registry([{...d,version:2}],families)),'unknown version');
 check(reject(()=>registry([{...d,damage:[{family:'void',amount:1,scaling:0}]}],families)),'unknown family');
 check(reject(()=>registry([{...d,damage:[d.damage[0],d.damage[0]]}],families)),'duplicate family');
 check(reject(()=>registry([{...d,cost:{stamina:-1,mana:0}}],families)),'invalid cost');
 check(reject(()=>registry([{...d,timing:{...d.timing,activeMs:NaN}}],families)),'invalid timing');
 check(reject(()=>registry([{...d,geometry:{...d.geometry,maxTargets:33}}],families)),'bounded geometry');
 check(reject(()=>registry([equipment],families)),'missing equipment action');
 check(reject(()=>registry([{...equipment,scope:'content'},d],families)),'fixture reference denied');
 check(reject(()=>registry([{...equipment,slot:'feet'},d],families)),'invalid weapon slot');
 check(reject(()=>registry([{...d,requirements:[{skillId:'skill:strength',level:100}]}],families)),'invalid requirement');
 check(reject(()=>registry([{...d,effects:['bad']}],families)),'invalid effects');
 const offense={physicalAttack:10,magicalAttack:4,criticalChance:.25,criticalDamage:2};
 const defense={mitigation:.2,blockReduction:.5,resistance:Object.fromEntries(families.map(f=>[f,0]))};defense.resistance.fire=.5;
 const input={definition:def,offense,defense,roll:.5,guard:'none',blockable:true,parryable:true};
 const close=(a,b)=>Math.abs(a-b)<1e-8;
 check(close(resolve(input,families).amount,28),'mixed typed damage');
 check(close(resolve({...input,roll:.1},families).amount,56),'critical');
 check(!resolve({...input,roll:.25},families).critical,'critical threshold');
 check(close(resolve({...input,guard:'block'},families).amount,14),'block reduction');
 check(resolve({...input,guard:'parry'},families).amount===0,'parry');
 check(close(resolve({...input,guard:'parry',parryable:false},families).amount,28),'unparryable');
 check(close(resolve({...input,guard:'block',blockable:false},families).amount,28),'unblockable');
 check(close(resolve({...input,defense:{...defense,resistance:{...defense.resistance,fire:-.5}}},families).amount,36),'vulnerability');
 check(close(resolve({...input,definition:{...def,power:'magical'}},families).amount,23.2),'magic scaling');
 check(resolve({...input,definition:{...def,critical:false},roll:0},families).critical===false,'critical ineligible');
 check(resolve({...input,definition:{...def,damage:[{family:'fire',amount:100000,scaling:10}]},offense:{...offense,physicalAttack:100000},roll:0},families).capped,'finite final cap');
 check(reject(()=>resolve({...input,roll:1},families)),'invalid random sample');
 check(reject(()=>resolve({...input,offense:{...offense,physicalAttack:Infinity}},families)),'nonfinite offense');
 check(reject(()=>resolve({...input,defense:{...defense,mitigation:2}},families)),'invalid mitigation');
 check(reject(()=>resolve({...input,defense:{...defense,resistance:{}}},families)),'missing resistance');
 check(JSON.stringify(resolve(input,families))===JSON.stringify(resolve({...input,definition:{...def,damage:[...def.damage].reverse()}},families)),'order deterministic');
 const req={version:1,worldId:'world:1',profileId:'profile:1',transactionId:'tx:1',actionId:'action:1',sourceId:'player:1',targetId:'mob:1',definitionId:def.id,amount:28,fixture:true};
 const res={...req,accepted:true,before:20,after:0,applied:20,terminal:'downed',permanentDefeat:false};
 check(!receipt(req,res).progressionCandidate,'fixture no progression');
 const real={...req,fixture:false},realReceipt={...res,fixture:false};
 check(receipt(real,realReceipt).progressionCandidate&&!receipt(real,realReceipt).permanentDefeat,'real down not permanent');
 check(receipt(real,{...realReceipt,terminal:'removed',permanentDefeat:true}).permanentDefeat,'authority permanent outcome');
 check(reject(()=>receipt(real,{...realReceipt,transactionId:'tx:2'})),'identity mismatch');
 check(reject(()=>receipt(real,{...realReceipt,applied:28})),'actual delta mismatch');
 check(reject(()=>receipt(real,{...realReceipt,permanentDefeat:true})),'downed is not permanent');
 check(reject(()=>receipt(real,{...realReceipt,accepted:false})),'rejected write no outcome');
 check(!receipt(real,{...realReceipt,accepted:false,after:20,applied:0,terminal:'none'}).progressionCandidate,'rejected receipt no progression');
 check(reject(()=>receipt(real,{...realReceipt,terminal:'none'})),'zero health without terminal rejected');
 check(reject(()=>receipt(real,{...realReceipt,worldId:'world:2'})),'wrong world rejected');
 check(reject(()=>receipt({...real,amount:10},realReceipt)),'over-applied damage rejected');
}
test('AV3 registry and AV4 typed damage',()=>cases((ok,name)=>assert.ok(ok,name),createCombatRegistry,resolveDamage,validateDamageReceipt,FAMILIES));
