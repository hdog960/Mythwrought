const tiny={radius:.2,height:.4,collision:'aabb'};
const obs=()=>({biome:'cave',light:.25,hazard:false,dayPhase:'night'});
function view(world,opts={}){return createExpansionOwnerView(world,{hasOwner:()=>true,observe:obs,overlayEpoch:()=>0,...opts});}
test('real VoxelWorld upper source and owner key admission, staged overlay invalidation',()=>{
 const base=new VoxelWorld(179),world=new Pack2LiveWorld(base),keys=new Set();
 assert.ok(world.set(0,31,0,BLOCK.AIR));assert.ok(world.set(0,30,0,BLOCK.STONE));
 keys.add(runtimeMeshKey(0,0,1));
 const v=view(world,{hasOwner:key=>keys.has(key)});
 assert.equal(expansionSupport(v.query,[.5,31,.5],tiny,'ground'),true);
 keys.clear();assert.equal(v.query.volume([.5,31,.5],tiny),'unknown');keys.add(runtimeMeshKey(0,0,1));
 const revision=v.revision();world.stagedNonblockCollision=()=>true;
 assert.ok(v.revision()>revision);assert.equal(v.query.volume([.5,31,.5],tiny),'solid');
 delete world.stagedNonblockCollision;
 assert.equal(v.query.volume([.5,31,.5],tiny),'clear');
});
test('actual crystal voxel habitat and canonical climb face, no invented cave facts',()=>{
 const world=arena({floor:-35});
 assert.ok(world.set(0,-35,0,BLOCK.CRYSTAL));
 const v=view(world),spec=APPROVED.find(x=>x.id==='crystal-snail');
 const cap=normalizeExpansionCapabilities(spec.id,{body:tiny,depth:[-100,-4],movement:['walk'],spawnSupport:['ground']});
 const p=[.5,-34,.5],facts=()=>readExpansionHabitatFacts(v,p,cap,spec);
 assert.deepEqual(facts(),{ 'crystal-floor':true,ground:true,darkness:true});
 assert.equal(expansionHabitatEligible(v.query,p,cap,spec,{facts,lightRange:[0,.5],observer:[8,-34,.5]}),true);
 assert.ok(world.set(0,-35,0,BLOCK.STONE));assert.equal(facts()['crystal-floor'],false);
 assert.ok(world.set(1,-34,0,BLOCK.STONE));
 assert.equal(expansionSupport(v.query,[.8,-34,.5],tiny,'climb-surface'),true);
 assert.ok(world.set(1,-34,0,BLOCK.AIR));
 assert.equal(expansionSupport(v.query,[.8,-34,.5],tiny,'climb-surface'),false);
 const hydra=APPROVED.find(x=>x.id==='abyssal-hydra');
 assert.equal(readExpansionHabitatFacts(v,p,{...cap,id:hydra.id},hydra)['natural-large-chamber'],false);
});
test('actual serialized original roster parity with explicit catalog, tames and bonded identities',()=>{
 const world=arena({floor:-3}),query=createWorldQuery(world,{resident:()=>true,observe:()=>({biome:'meadow',light:.65,hazard:false})});
 const engine=new MobEngine(query,42,{maxEntities:32,maxActive:8,catalog:legacyIndex});
 const behavior=new BehaviorController(engine,query),combat=new MobCombat(engine,query,behavior);
 const companions=new CompanionManager(engine,query,combat),animals=new AnimalInteractions(engine,query);
 const owner=new DemoTarget([-.5,-2,.5]),before=JSON.stringify(world.base.save());
 const glow=engine.spawn('glownewt',[.5,-2,.5]),horse=engine.spawn('horse',[-.5,-2,1.5]);
 assert.ok(companions.befriend(glow,owner));assert.ok(animals.tame(horse,owner));
 const bytes=serializeRoster({engine,companions,animals});
 const restored=restoreRoster(bytes,query,null,undefined,{catalog:legacyIndex});
 assert.equal(serializeRoster(restored),bytes);assert.ok(restored.animals.isTamed(horse,owner));
 assert.deepEqual(restored.companions.slots(),companions.slots());
 assert.equal(serializeRoster(restoreRoster(bytes,query)),bytes);
 assert.throws(()=>restoreRoster(bytes,query,null,undefined,{catalog:{...legacyIndex,size:100}}));
 assert.equal(JSON.stringify(world.base.save()),before);
});
