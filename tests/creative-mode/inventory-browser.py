"""M3 real system Chromium layout and touch assertions; detached feature fixture only."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import base64
ROOT=Path(__file__).resolve().parents[2]/'src'/'creative-mode'
HTML=(ROOT/'preview.html').read_text().replace('<link rel="stylesheet" href="./preview.css">','').replace('<script type="module" src="./preview.mjs"></script>','')
CSS=(ROOT/'preview.css').read_text()
def uri(text):return 'data:text/javascript;base64,'+base64.b64encode(text.encode()).decode()
ADAPTER=uri((ROOT/'adapter-contract.mjs').read_text())
MODEL=uri((ROOT/'inventory-model.mjs').read_text().replace("from './adapter-contract.mjs'",f"from '{ADAPTER}'"))
JS=(ROOT/'preview.mjs').read_text()
for name,data in [('ux-state.mjs',uri((ROOT/'ux-state.mjs').read_text())),('flight-model.mjs',uri((ROOT/'flight-model.mjs').read_text())),
('inventory-model.mjs',MODEL),('inventory-fixture.mjs',uri((ROOT/'inventory-fixture.mjs').read_text()))]:
 JS=JS.replace(f"from './{name}'",f"from '{data}'")
def load(page):
 page.set_content(HTML,wait_until='domcontentloaded')
 page.add_style_tag(content=CSS)
 page.add_script_tag(type='module',content=JS)
 page.wait_for_function("document.querySelectorAll('.slot').length===6")
def bound(page,selector):return page.locator(selector).bounding_box()
SIZES=[(568,320),(667,375),(844,390),(932,430),(956,440),(1180,520)]
checks=0
def check(condition,reason):
 global checks
 checks+=1
 assert condition,reason
ART=Path('artifacts/creative-mode');ART.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 for w,h in SIZES:
  context=browser.new_context(viewport={'width':w,'height':h},device_scale_factor=1,is_mobile=True,has_touch=True)
  page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  load(page)
  page.locator('#creativeMode').click();page.locator('.slot[data-slot="3"]').click();page.locator('#inventoryButton').click()
  check(page.locator('#sampleItems .sample-item').count()==4,'M1 sample inventory regression')
  check(page.locator('#registryFixtureSource').is_visible(),'no fixture switch')
  page.locator('#registryFixtureSource').click()
  check(page.locator('#registryFixtureSource').get_attribute('aria-pressed')=='true','fixture mode not active')
  check(page.locator('#catalogScroller').get_attribute('data-total-items')=='1632','fixture snapshot missing')
  check('NOT LIVE' in page.locator('#inventoryOrigin').inner_text(),'fixture presented as live')
  check(page.locator('#sampleItems').is_hidden(),'samples not hidden')
  check(page.locator('#catalogScroller').is_visible(),'virtual scroller not visible')
  count=int(page.locator('#catalogScroller').get_attribute('data-rendered'))
  check(0<count<=36,'unbounded DOM')
  check(page.locator('.catalog-tile').count()==count,'render count mismatch')
  check(page.locator('#catalogCategories button').count()==6,'dynamic categories missing')
  panel=bound(page,'#inventoryPanel');minimap=bound(page,'#miniMapReservation');scroll=bound(page,'#catalogScroller')
  check(panel['x']+panel['width']<=minimap['x']-2,'inventory covers upper-right map')
  check(scroll['height']>=30,'compact viewport inventory clipped')
  check(scroll['y']>=panel['y']+15,'inventory scroller above panel')
  check(scroll['y']+scroll['height']<=panel['y']+panel['height'],'inventory scroller past panel')
  first=page.locator('.catalog-tile').first.get_attribute('data-placeable-key')
  page.locator('#catalogScroller').evaluate('(e)=>{e.scrollTop=25000;e.dispatchEvent(new Event("scroll"))}')
  page.wait_for_timeout(30)
  check(first!=page.locator('.catalog-tile').first.get_attribute('data-placeable-key'),'virtual scroll did not update')
  check(int(page.locator('#catalogScroller').get_attribute('data-rendered'))<=36,'scroll over-created DOM')
  page.locator('#inventorySearch').fill('fixture 013')
  check(page.locator('#catalogScroller').get_attribute('data-matches')=='100','search mismatch')
  page.locator('#catalogCategories button[data-catalog-category="Stone"]').click()
  check(page.locator('#catalogScroller').get_attribute('data-matches')=='20','category + query mismatch')
  check(page.locator('.catalog-tile').count()>=1,'no filtered rows shown')
  tile=page.locator('.catalog-tile').first;name=tile.locator('b').inner_text();b=tile.bounding_box()
  page.touchscreen.tap(b['x']+b['width']/2,b['y']+b['height']/2)
  check(name in page.locator('.slot[data-slot="3"]').get_attribute('aria-label'),'touch assignment failed')
  check('NOT LIVE' in page.locator('#announcement').inner_text(),'mock assignment misrepresented')
  page.locator('#closeInventory').click()
  check(page.locator('#inventoryPanel').is_hidden(),'drawer did not close')
  check(name in page.locator('.slot[data-slot="3"]').get_attribute('aria-label'),'hotbar lost fixture ID')
  page.keyboard.press('5')
  check(page.locator('.slot[data-slot="4"]').get_attribute('aria-pressed')=='true','keyboard slot selection failed')
  page.locator('#inventoryButton').click()
  page.locator('#catalogViewport .catalog-tile').first.click()
  check('fixture' in page.locator('.slot[data-slot="4"]').get_attribute('aria-label').lower(),'keyboard selection assigned stale slot')
  page.locator('#closeInventory').click()
  page.locator('.slot[data-slot="1"]').click()
  check(page.locator('.slot[data-slot="1"]').get_attribute('aria-pressed')=='true','selected slot mismatch')
  page.locator('#inventoryButton').click()
  check(page.locator('#inventorySearch').input_value()=='fixture 013','catalog filter not retained')
  page.locator('#clearHotbar').click()
  check('fixture' not in page.locator('.slot[data-slot="1"]').get_attribute('aria-label').lower(),'clear did not work')
  page.locator('#sampleSource').click()
  check(page.locator('.sample-item').count()==4,'M1 samples not preserved')
  check(page.locator('#sampleItems').is_visible(),'samples not restored')
  check(page.locator('#catalogScroller').is_hidden(),'fixture list not hidden')
  check(page.locator('#inventoryOrigin').inner_text().startswith('UX samples'),'provenance not restored')
  check(not errors,f'JavaScript errors at {w}x{h}: {errors}')
  if w in (568,956):
   page.locator('#registryFixtureSource').click()
   page.locator('#inventorySearch').fill('')
   page.locator('#catalogCategories button[data-catalog-category="all"]').click()
   page.screenshot(path=str(ART/f'm3-registry-{w}x{h}.png'))
  context.close()
 browser.close()
print(f'PASS: {checks} real Chromium M3 assertions across {len(SIZES)} landscape sizes')
