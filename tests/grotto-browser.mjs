// MYTHWROUGHT Gate A — genuine mobile-emulated Chromium grotto and GPU-fault audit.
// Real game rendering, real WebGL buffers, real save keys; not actual iPhone Safari.
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:[
 '--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'
]});
const context=await browser.newContext({viewport:{width:932,height:430},
 deviceScaleFactor:1,hasTouch:true,isMobile:true});
const page=await context.newPage(),errors=[],missing=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400)missing.push(r.status()+' '+r.url());});
const saved=()=>page.evaluate(()=>localStorage.getItem('mythwrought-v002-world-179'));
const loaded=()=>page.waitForFunction(()=>Number(document.querySelector('#scene')?.dataset.loadedChunks)===25&&
  Number(document.querySelector('#scene')?.dataset.pendingChunks)===0,null,{timeout:40000});
const data=()=>page.evaluate(()=>{
 const c=document.querySelector('#scene'),world=c.getBoundingClientRect(),
   left=document.querySelector('.left').getBoundingClientRect(),
   right=document.querySelector('.right').getBoundingClientRect();
 return {count:Number(c.dataset.loadedChunks),pending:Number(c.dataset.pendingChunks),
  gaps:[world.left-left.right,right.left-world.right],
  center:world.width,frame:Number(c.dataset.renderedFrames),
  stats:window.__mythwroughtTest.snapshot()};
});
try{
 await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
 await loaded();
 assert.equal(await saved(),null,'Starting world unexpectedly written by decorative art');
 const cave=await page.evaluate(async()=>{
   const {VoxelWorld,terrainHeight,baseBlock,CHUNK_SIZE,WORLD_MIN_Y,WORLD_MAX_Y,BLOCK}
     =await import('./src/voxel.mjs');
   const {grottoAccentVertices}=await import('./src/grotto.mjs');
   const w=new VoxelWorld(179),details=[];
   for(let cx=-2;cx<=2;cx++)for(let cz=-2;cz<=2;cz++){
     const mesh=grottoAccentVertices(w,cx,cz,{
       chunkSize:CHUNK_SIZE,minY:WORLD_MIN_Y,maxY:WORLD_MAX_Y,
       heightAt:terrainHeight,baseAt:baseBlock,
       air:BLOCK.AIR,stone:BLOCK.STONE,ore:BLOCK.ORE
     });
     for(let p=0;p<mesh.length;){
       const x=Math.floor(mesh[p]),y=Math.floor(mesh[p+1]),z=Math.floor(mesh[p+2]);
       details.push({x,y,z,cx,cz});
       const firstMat=mesh[p+8];
       p+=firstMat===10?36*9:12*9;
     }
   }
   const candidate=details.find(d=>{
     for(const [dx,dz] of [[1,0],[-1,0],[0,1],[0,-1]])
       if(w.get(d.x+dx,d.y,d.z+dz)===BLOCK.AIR&&
         w.get(d.x+dx,d.y+1,d.z+dz)===BLOCK.AIR&&
         w.get(d.x+dx,d.y-1,d.z+dz)!==BLOCK.AIR)return true;
     return false;
   })||details[0];
   if(!candidate)return {count:0};
   const neighbor=[[1,0],[-1,0],[0,1],[0,-1]]
     .find(([dx,dz])=>w.get(candidate.x+dx,candidate.y,candidate.z+dz)===BLOCK.AIR&&
       w.get(candidate.x+dx,candidate.y+1,candidate.z+dz)===BLOCK.AIR&&
       w.get(candidate.x+dx,candidate.y-1,candidate.z+dz)!==BLOCK.AIR);
   return {count:details.length,candidate,
     viewpoint:neighbor?{x:candidate.x+neighbor[0],y:candidate.y,z:candidate.z+neighbor[1]}:
       {x:candidate.x,y:candidate.y,z:candidate.z}};
 });
 assert.ok(cave.count>0&&cave.candidate,'No underground grotto details on original seed 179');
 const {candidate,viewpoint}=cave;
 await page.evaluate(({candidate,viewpoint})=>{
   const dev=window.__mythwroughtTest;
   dev.teleportCave(viewpoint.x,viewpoint.y,viewpoint.z);
   dev.aimAt(candidate.x,candidate.y,candidate.z);
 },{candidate,viewpoint});
 await loaded();
 const underground=await data();
 assert.ok(underground.gaps.every(n=>n>=-2),'Underground art obstructs landscape grips');
 assert.ok(underground.center>=932*.45);
 assert.equal(underground.count,25);
 assert.equal(await saved(),null,'Rendering underground geometry modified canonical save bytes');
 await mkdir('artifacts',{recursive:true});
 await page.screenshot({path:'artifacts/mythwrought-v010-natural-grotto.png'});

 // Prove real original edits remove a natural-cave mushroom/crystal, including
 // when the scene is regenerated by the existing WebGL chunk system.
 const beforeBlock=await page.evaluate(({x,y,z})=>window.__mythwroughtTest.block(x,y,z),
   candidate);
 assert.equal(beforeBlock,0);
 await page.evaluate(({x,y,z})=>window.__mythwroughtTest.placeFixture(x,y,z,3),candidate);
 assert.equal(await page.evaluate(({x,y,z})=>window.__mythwroughtTest.block(x,y,z),candidate),3);
 assert.ok((await saved()).includes('['+[candidate.x,candidate.y,candidate.z,3].join(',')+']'));
 await page.screenshot({path:'artifacts/mythwrought-v010-grotto-blocked.png'});
 await page.reload({waitUntil:'networkidle'});
 await loaded();
 assert.equal(await page.evaluate(({x,y,z})=>window.__mythwroughtTest.block(x,y,z),candidate),3,
   'Reload lost original schema-1 cave edit');
 const savedBeforeFault=await saved();

 // Inject one real WebGL bufferData exception during an edit. The original
 // edit action must roll back and the old GPU chunk buffers remain readable.
 await page.evaluate(()=>{
   const gl=document.querySelector('#scene').getContext('webgl2'),
     original=gl.bufferData.bind(gl);
   let faultCount=1;
   gl.bufferData=function(...args){
     if(faultCount>0&&args[0]===gl.ARRAY_BUFFER){
       faultCount--;throw Error('Injected one-time GPU staging failure');
     }
     return original(...args);
   };
 });
 const oldChunks=(await data()).stats.chunks;
 const faultResult=await page.evaluate(({x,y,z})=>{
   try{window.__mythwroughtTest.placeFixture(x,y,z,0);return 'unexpected success';}
   catch(error){return String(error.message||error);}
 },candidate);
 assert.match(faultResult,/Injected one-time GPU staging failure/);
 assert.equal(await saved(),savedBeforeFault,'Failed GPU edit altered verified canonical save');
 assert.equal(await page.evaluate(({x,y,z})=>window.__mythwroughtTest.block(x,y,z),candidate),3);
 assert.deepEqual((await data()).stats.chunks,oldChunks,
   'Failed buffer swap invalidated previously loaded chunk keys');

 // A subsequent healthy edit must still work and write the original format.
 await page.evaluate(({x,y,z})=>window.__mythwroughtTest.placeFixture(x,y,z,0),candidate);
 assert.equal(await page.evaluate(({x,y,z})=>window.__mythwroughtTest.block(x,y,z),candidate),0);
 const savedAfterRecovery=await saved();
 assert.equal(JSON.parse(savedAfterRecovery).schema,1);
 assert.ok(!JSON.parse(savedAfterRecovery).edits.some(r=>
  r[0]===candidate.x&&r[1]===candidate.y&&r[2]===candidate.z));
 // The screenshot should show the restored original cave, not the spawn
 // surface where a test reload starts the player.
 await page.evaluate(({candidate,viewpoint})=>{
   const dev=window.__mythwroughtTest;
   dev.teleportCave(viewpoint.x,viewpoint.y,viewpoint.z);
   dev.aimAt(candidate.x,candidate.y,candidate.z);
 },{candidate,viewpoint});
 await loaded();
 await page.screenshot({path:'artifacts/mythwrought-v010-grotto-after-recovery.png'});

 // WebGL also reports failures as error codes WITHOUT throwing. Prove that
 // this path rolls back an edit and keeps the last healthy chunk buffer.
 await page.evaluate(()=>{
   const gl=document.querySelector('#scene').getContext('webgl2'),
     originalUpload=gl.bufferData.bind(gl),originalError=gl.getError.bind(gl);
   let pendingError=false,once=true;
   gl.bufferData=function(...args){
     const result=originalUpload(...args);
     if(once&&args[0]===gl.ARRAY_BUFFER){once=false;pendingError=true;}
     return result;
   };
   gl.getError=function(){
     if(pendingError){pendingError=false;return gl.OUT_OF_MEMORY;}
     return originalError();
   };
 });
 const beforeSilentError=await saved(),oldGpuChunks=(await data()).stats.chunks;
 const silentError=await page.evaluate(({x,y,z})=>{
   try{window.__mythwroughtTest.placeFixture(x,y,z,3);return 'unexpected success';}
   catch(error){return String(error.message||error);}
 },candidate);
 assert.match(silentError,/WebGL buffer upload error/);
 assert.equal(await saved(),beforeSilentError,
   'Silent GPU OUT_OF_MEMORY error modified canonical schema-1 world');
 assert.equal(await page.evaluate(({x,y,z})=>window.__mythwroughtTest.block(x,y,z),candidate),0);
 assert.deepEqual((await data()).stats.chunks,oldGpuChunks,
   'Silent WebGL error destroyed a previously good chunk buffer');

 // Separate genuine new-chunk upload failure must back off, allow other chunks
 // to stream, recover automatically and keep rendering within 5x5 memory bound.
 await page.evaluate(()=>{
   const gl=document.querySelector('#scene').getContext('webgl2'),
     original=gl.bufferData.bind(gl);
   let once=true;
   gl.bufferData=function(...args){
     if(once&&args[0]===gl.ARRAY_BUFFER){
       once=false;throw Error('Injected streaming GPU failure');
     }
     return original(...args);
   };
   window.__mythwroughtTest.teleport(-52.5,-47.5);
 });
 await page.waitForFunction(()=>window.__mythwroughtTest.snapshot().gpuRetry.failures>=1,
   null,{timeout:30000});
 await loaded();
 const after=await data();
 assert.equal(after.count,25);
 assert.equal(after.pending,0);
 assert.ok(after.stats.gpuRetry.recovered>=1,'Deferred chunk never recovered');
 assert.ok(after.stats.gpuRetry.pendingRetries===0);
 assert.ok(after.gaps.every(n=>n>=-2));
 assert.equal(await saved(),savedAfterRecovery,'GPU streaming corrupted saved cave edits');
 await page.screenshot({path:'artifacts/mythwrought-v010-gpu-recovered.png'});
 assert.deepEqual(errors,[],'Browser runtime errors');
 assert.deepEqual(missing,[],'Missing assets');
 console.log('PASS Gate A natural luminous grotto, original cave edit/reload, GPU rollback and automatic bounded retry; saves and side grips intact');
}finally{await browser.close();}
