import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createPoiseTracker} from '../src/age-of-valor/poise.mjs';
import {createStatusRegistry,createStatusSession} from '../src/age-of-valor/status.mjs';
import {createGuardDrain} from '../src/age-of-valor/guard-drain.mjs';
function cases(check,poise,registry,session,drain){
 const reject=f=>{try{f();return false}catch{return true}};
 const p=poise({worldEpoch:1,maximum:1000,regenPerSecond:500,regenDelayMs:100,staggerMs:200,immunityMs:300,criticalMultiplier:2});
 const hit=(sequence,force,extra={})=>({worldEpoch:1,at:p.snapshot().clock,sequence,force,accepted:true,critical:false,resistance:0,...extra});
 check(p.impact(hit(1,400)).kind==='absorbed'&&p.snapshot().poise===600,'poise depletion');
 check(p.impact(hit(1,500)).kind==='invalid','duplicate impact');
 check(p.impact(hit(2,500,{resistance:1})).kind==='resisted','full resistance');
 p.advance(100);check(p.snapshot().poise===600,'regen delay');p.advance(200);check(p.snapshot().poise===700,'regen');
 check(p.impact(hit(3,350,{critical:true})).kind==='stagger-proposal','critical break');
 const deadline=p.snapshot().protectedUntil;
 check(p.impact(hit(4,1000)).kind==='protected'&&p.snapshot().protectedUntil===deadline,'no extension');
 p.advance(499);check(p.impact(hit(5,1000)).kind==='protected','immunity boundary');
 p.advance(1);check(p.impact(hit(6,1000)).kind==='stagger-proposal','next eligible break');
 check(p.advance(100,true).snapshot.clock===800,'paused poise');
 p.close();check(p.impact(hit(7,1)).kind==='invalid','closed poise');
 const d={id:'fixture:burn',version:1,scope:'fixture',kind:'burning',durationMs:500,stacking:'stack',maxStacks:2,resistanceFamily:'fire',tickKind:'damage',tickAmount:5,tickMs:100,resource:null,modifiers:[{stat:'mitigation',delta:-.1}]};
 const q={...d,id:'fixture:regen',kind:'regeneration',tickKind:'heal',stacking:'refresh',maxStacks:1,modifiers:[]};
 const reg=registry([d,q]);const s=session({registry:reg,worldEpoch:1,targetId:'mob:1',fixture:true});
 const effect=(sequence,extra={})=>({sequence,worldEpoch:1,targetId:'mob:1',sourceId:'player:1',effectId:d.id,at:s.snapshot().clock,verified:true,resistance:0,...extra});
 check(s.apply(effect(1)).ok,'apply');check(!s.apply(effect(1)).ok,'duplicate');
 check(s.apply(effect(2)).ok&&s.apply(effect(3)).ok&&s.snapshot().effects[0].stacks===2,'stack cap');
 check(s.modifiers()[0].delta===-.2,'stack modifier');
 check(s.advance(100).events[0].amount===10,'tick magnitude');
 check(s.apply(effect(4,{effectId:q.id,resistance:1})).reason==='resisted','status resistance');
 check(s.apply(effect(5,{effectId:q.id,resistance:.5})).ok,'shortened duration');
 check(s.advance(100,{paused:true}).snapshot.clock===100,'pause');
 const e=s.advance(250).events;
 check(e.filter(x=>x.kind==='heal').length===2&&e.some(x=>x.type==='expired'&&x.effectId===q.id),'heal ticks and expiry');
 check(s.advance(150).events.some(x=>x.type==='expired'&&x.effectId===d.id),'expiration');
 check(s.snapshot().effects.length===0&&s.modifiers().length===0,'expired modifier gone');
 check(!s.apply(effect(6,{verified:false})).ok,'unverified application');
 check(s.apply(effect(7)).ok&&s.advance(0,{alive:false}).snapshot.closed,'death clears');
 check(!s.advance(100).ok,'no dead ticks');
 check(reject(()=>registry([d,d])),'duplicate status definition');
 check(reject(()=>registry([{...d,tickMs:0}])),'zero tick interval');
 check(reject(()=>registry([{...d,maxStacks:9}])),'stack bound');
 check(reject(()=>registry([{...d,modifiers:[{stat:'health',delta:1}]}])),'no health stat writes');
 const a=session({registry:reg,worldEpoch:1,targetId:'mob:1',fixture:true}),b=session({registry:reg,worldEpoch:1,targetId:'mob:1',fixture:true});
 const init={...effect(1),at:0};a.apply(init);b.apply(init);
 const whole=a.advance(500).events,split=[...b.advance(100).events,...b.advance(200).events,...b.advance(200).events];
 check(JSON.stringify(whole)===JSON.stringify(split),'partition invariant');
 const real=session({registry:reg,worldEpoch:1,targetId:'mob:1',fixture:false});check(!real.apply(init).ok,'fixture denied live');
 let st={clock:0,state:'blocking',actionId:1},charges=0;
 const hold=drain({intervalMs:100,cost:100,breakMs:80,readState:()=>st,charge:()=>++charges===2?{ok:false,reason:'guard-broken'}:{ok:true,reason:'guard-paid'}});
 check(hold.synchronize().next===100,'hold schedule');st.clock=100;
 check(hold.synchronize().next===200&&charges===1,'one pulse');
 check(hold.synchronize().next===200&&charges===1,'no duplicate pulse');
 st.clock=200;check(hold.synchronize().reason==='guard-broken','hold guard break');
 st={clock:201,state:'idle',actionId:null};check(hold.synchronize().reason==='idle','release clears');
 const late=drain({intervalMs:100,cost:100,breakMs:80,readState:()=>st,charge:()=>{throw Error('must not charge')}});
 st={clock:300,state:'blocking',actionId:2};late.synchronize();st.clock=401;
 check(late.synchronize().reason==='authority-uncertain','missed boundary fails closed');
}
test('AV9 poise, AV10 statuses and held guard drain',()=>cases((ok,name)=>assert.ok(ok,name),createPoiseTracker,createStatusRegistry,createStatusSession,createGuardDrain));
