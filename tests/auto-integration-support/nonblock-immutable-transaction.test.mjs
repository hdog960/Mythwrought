import test from 'node:test';
import assert from 'node:assert/strict';
import {auditImmutableRemoval} from '../../src/auto-integration-support/nonblock-immutable-transaction.mjs';
const objects=[{id:'scene48:one'},{id:'nonblock:d:two'}];
const keyOf=o=>o.id;
const snapshot=os=>({active:os.map(o=>({...o})),tombstones:[]});
const remove=(s,k)=>({active:s.active.filter(o=>o.id!==k),tombstones:[...s.tombstones,k]});
const restore=s=>s.active;
const tombstonesOf=s=>s.tombstones;
const run=(over={})=>auditImmutableRemoval({objects,keyOf,snapshot,remove,restore,tombstonesOf,...over});
test('valid synthetic transaction never claims live',()=>{const r=run();assert.equal(r.ok,true);assert.equal(r.live,false);assert.equal(r.breakabilityReady,false)});
test('missing callback fails',()=>assert.match(run({restore:null}).errors.join(),/missing-restore/));
test('duplicate identity fails',()=>assert.match(run({objects:[objects[0],objects[0]]}).errors.join(),/duplicate-key/));
test('invalid key fails',()=>assert.match(run({keyOf:()=> '7'}).errors.join(),/invalid-key/));
test('input mutation fails',()=>assert.match(run({remove:(s,k)=>{s.active.shift();s.tombstones.push(k);return {...s}}}).errors.join(),/snapshot-mutated/));
test('alias fails',()=>assert.match(run({remove:s=>s}).errors.join(),/snapshot-aliased/));
test('missing tombstone fails',()=>assert.match(run({remove:(s,k)=>({...s,active:s.active.filter(o=>o.id!==k)})}).errors.join(),/missing-tombstone/));
test('neighbor tombstone fails',()=>assert.match(run({remove:(s,k)=>({...remove(s,k),tombstones:[k,objects[1].id]})}).errors.join(),/neighbor-tombstoned/));
test('respawn fails',()=>assert.match(run({restore:()=>objects}).errors.join(),/respawned/));
test('neighbor disappearance fails',()=>assert.match(run({restore:()=>[]}).errors.join(),/neighbor-lost/));
test('throw fails closed',()=>assert.match(run({remove:()=>{throw Error('x')}}).errors.join(),/callback-threw/));
