export const PLAINS_MODEL_IDS=Object.freeze(Object.keys(authors));
export function buildPlainsModel(id){
 if(!Object.hasOwn(authors,id))return undefined;
 return buildBeastMesh(authors[id]);
}
export function plainsModelEnvelope(id){
 const mesh=buildPlainsModel(id);if(!mesh)return undefined;
 const info=inspectBeastMesh(mesh);
 // Static mesh envelope rounded upward with conservative initial margin.
 // Species-specific collision and shader motion still require qualification.
 const body=Object.freeze({radius:Math.ceil((info.radius+.15)*100)/100,height:Math.ceil((info.maxY+.30)*100)/100,collision:'aabb'});
 return Object.freeze({id,body,info});
}
