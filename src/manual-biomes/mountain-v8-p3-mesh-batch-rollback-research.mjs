// Mountain V8 isolated CPU-only mesh batch / rollback research. NEVER
// imported by production. No V8 runtime dispatch, registered block IDs,
// GPU calls, save writes, old-world edits, or publication into a live map.
// Mirrors current-main main.mjs refreshEditedMeshes' stage-before-publish
// contract using a NEW projected Map, not actual WebGL buffer handles.
// Original M7 P3 radius-three color cues are deliberately NOT inherited.
import {CHUNK_SIZE,chunkCoord} from '../voxel.mjs';
import {editAffectedChunks} from '../chunks.mjs';
import {depthMeshKey,verticalEditSections,sectionForY}
  from '../depth.mjs';
import {validateChunkUploadBytes,MAX_CHUNK_UPLOAD_BYTES}
  from '../gpu-recovery.mjs';
import {V8_P3_SOURCE_HEAD}
  from './mountain-v8-p3-uplift-and-halo-audit.mjs';

const freeze=Object.freeze;
const int=Number.isSafeInteger;
export const V8_RESEARCH_MAX_SOURCE_COLUMNS=5;
export const V8_RESEARCH_MAX_PHYSICAL_CELLS=90;
export const V8_RESEARCH_MAX_LOADED_REFRESH=16;
export const V8_RESEARCH_MAX_STAGE_BYTES=16*1024*1024;
const key=({cx,cz,section})=>depthMeshKey(cx,cz,section);
const noPermission=freeze({
  oldM7P3ColorHaloInherited:false,
  newV8ColorHaloOwnerApproved:false,
  actualGPUUploadPerformed:false,
  originalGPUBufferDeleted:false,
  originalWorldWritten:false,
  savedSchema1Changed:false,
  sourcePack2Pack3ManualCachesTouched:false,
  newV8MaterialIdsRegistered:0,
  creatorApprovedGameplay:false,
  safeToIntegrate:false
});
/** Derived strictly from original source editAffectedChunks and
 * verticalEditSections. This is a coordinate-only preview, NOT source proof.
 */
export function previewMountainV8OriginalDirtyKeys(x,y,z){
  if(![x,y,z].every(int)||sectionForY(y)===null)
    throw Error('Original mesh edit coordinates outside source');
  const coords=editAffectedChunks(x,z);
  const sections=verticalEditSections(y);
  if(coords.length>3||sections.length<1||sections.length>2)
    throw Error('Original dirty-chunk bound changed');
  const entries=[];
  for(const section of sections)for(const {cx,cz} of coords)
    entries.push(freeze({cx,cz,section,key:depthMeshKey(cx,cz,section)}));
  const seen=new Set(entries.map(x=>x.key));
  if(seen.size!==entries.length||CHUNK_SIZE!==16||
     chunkCoord(x)!==Math.floor(x/CHUNK_SIZE)||
     chunkCoord(z)!==Math.floor(z/CHUNK_SIZE))
    throw Error('Original mesh-coordinate identity changed');
  return freeze({x,y,z,originalSourceDirtyKeys:freeze(entries),
    originalGeometryOnly:true,oldM7P3ColorHaloInherited:false,
    safeToIntegrate:false});
}
/** ALL proofs must first be freshly generated by the current-main two-
 * checkout source audit auditMountainV8P3Uplift; strings in a proof are NOT
 * cryptographic authentication and no runtime authority is ever granted.
 * existingLoadedChunks is caller-owned and is NEVER written by this method.
 */
export function planMountainV8ResearchMeshBatch(proofs,existingLoadedChunks){
  if(!Array.isArray(proofs)||proofs.length<1||
     proofs.length>V8_RESEARCH_MAX_SOURCE_COLUMNS||
     !(existingLoadedChunks instanceof Map))
    throw Error('Invalid detached original-source batch');
  const candidates=new Map(),observedSources=new Set();
  let materialCells=0,seed=null;
  for(const proof of proofs){
    if(!proof||proof.sourceMainHead!==V8_P3_SOURCE_HEAD||
       proof.originalSourceUpliftChecked!==true||
       proof.oldM7ColorHaloClaimed!==false||
       proof.V8ColorAndGPUInvalidationOwnerApprovalRequired!==true||
       proof.safeToIntegrate!==false||
       proof.runtimeActivationAuthorized!==false||
       proof.newV8MaterialIdsRegistered!==0||
       proof.originalWorldWrites!==0||
       proof.originalWorldSaveRewrites!==0||
       ![proof.seed,proof.x,proof.z,proof.originalLegacyTop,
         proof.proposedV8Top,proof.sourcePhysicalCells].every(int)||
       !Array.isArray(proof.sections)||proof.sections.length!==1||
       proof.sections[0]!==0||
       !Array.isArray(proof.geometryMeshKeys)||
       !Array.isArray(proof.geometryChunkCoordinates)||
       proof.sourcePhysicalCells<1||proof.sourcePhysicalCells>18||
       !Array.isArray(proof.originalPhysicalDescriptorMaterials)||
       proof.originalPhysicalDescriptorMaterials.length!==proof.sourcePhysicalCells)
      throw Error('Unverifiable original V8 uplift source proof');
    if(seed!==null&&seed!==proof.seed)throw Error('Mixed original-world seeds');
    seed=proof.seed;
    const source=proof.x+','+proof.z;
    if(observedSources.has(source))throw Error('Duplicated V8 column source');
    observedSources.add(source);
    materialCells+=proof.sourcePhysicalCells;
    if(materialCells>V8_RESEARCH_MAX_PHYSICAL_CELLS)
      throw Error('Unbounded V8 physical cells');
    const expected=editAffectedChunks(proof.x,proof.z);
    const expectedKeys=expected.map(({cx,cz})=>depthMeshKey(cx,cz,0));
    if(proof.geometryChunkCoordinates.length!==expected.length||
       proof.geometryMeshKeys.length!==expectedKeys.length||
       JSON.stringify(proof.geometryChunkCoordinates)!==JSON.stringify(expected)||
       JSON.stringify(proof.geometryMeshKeys)!==JSON.stringify(expectedKeys))
      throw Error('Original geometry dirty chunk provenance mismatch');
    for(const {cx,cz} of expected){
      const item=freeze({cx,cz,section:0,key:depthMeshKey(cx,cz,0)});
      candidates.set(item.key,item);
    }
  }
  const keys=[...candidates.values()],loaded=[],unloaded=[];
  if(keys.length>V8_RESEARCH_MAX_LOADED_REFRESH)
    throw Error('Unbounded owner dirty-chunk set');
  for(const item of keys){
    if(existingLoadedChunks.has(item.key))loaded.push(item);
    else unloaded.push(item);
  }
  const originals=freeze(loaded.map(item=>freeze({
    key:item.key,originalEntry:existingLoadedChunks.get(item.key)})));
  return freeze({seed,sourceMainHead:V8_P3_SOURCE_HEAD,
    sourceColumns:proofs.length,sourcePhysicalCells:materialCells,
    originalDirtyKeys:freeze(keys),
    loaded:freeze(loaded),unloaded:freeze(unloaded),
    originalEntries:originals,oldM7P3ColorHaloInherited:false,
    requiresOwnerApprovedV8ColorAndGpuRules:true,
    ...noPermission});
}
/** Prepares a hypothetical new Map of CPU mesh metadata. It never executes
 * a GPU upload, touches an original Map entry or deletes old live buffers.
 * On ANY builder/packed-stride/size/total-budget failure it returns a
 * REJECTED preview, with no partially published replacements.
 * Builders are source-read-only callbacks; actual purity must be separately
 * proved for each exact checkout, not inferred from this code.
 */
export function stageMountainV8ResearchCpuPreview(plan,existingLoadedChunks,{
  buildOpaque,buildWater=()=>new Float32Array(0),
  stageTotalLimitBytes=V8_RESEARCH_MAX_STAGE_BYTES
}={}){
  const reject=(reason)=>freeze({status:'rejected',reason,
    stageCount:0,projectedChunks:null,bytesStaged:0,...noPermission});
  if(!plan||plan.safeToIntegrate!==false||
     plan.sourceMainHead!==V8_P3_SOURCE_HEAD||
     !Array.isArray(plan.loaded)||
     !Array.isArray(plan.originalEntries)||
     !(existingLoadedChunks instanceof Map)||
     typeof buildOpaque!=='function'||typeof buildWater!=='function'||
     !int(stageTotalLimitBytes)||stageTotalLimitBytes<0||
     stageTotalLimitBytes>V8_RESEARCH_MAX_STAGE_BYTES)
    return reject('invalid-source-stage-input');
  if(plan.loaded.length!==plan.originalEntries.length||
     plan.loaded.length>V8_RESEARCH_MAX_LOADED_REFRESH||
     plan.originalEntries.some((x,i)=>x.key!==plan.loaded[i].key||
       !existingLoadedChunks.has(x.key)||
       existingLoadedChunks.get(x.key)!==x.originalEntry))
    return reject('original-loaded-chunks-changed');
  const beforeSize=existingLoadedChunks.size;
  const ready=[];
  let bytes=0;
  try{
    for(const item of plan.loaded){
      const opaque=buildOpaque(item.cx,item.cz,item.section);
      const water=buildWater(item.cx,item.cz,item.section);
      const opaqueBytes=validateChunkUploadBytes(opaque,MAX_CHUNK_UPLOAD_BYTES);
      const waterBytes=validateChunkUploadBytes(water,MAX_CHUNK_UPLOAD_BYTES);
      bytes+=opaqueBytes+waterBytes;
      if(bytes>stageTotalLimitBytes)throw Error('CPU research staging aggregate budget');
      ready.push(freeze({key:item.key,cx:item.cx,cz:item.cz,
        section:item.section,
        opaqueBytes,waterBytes,opaqueVertexCount:opaque.length/9,
        waterVertexCount:water.length/9}));
    }
    if(existingLoadedChunks.size!==beforeSize||
       plan.originalEntries.some(x=>existingLoadedChunks.get(x.key)!==x.originalEntry))
      throw Error('Original source changed during CPU preview');
  }catch{return reject('source-cpu-stage-or-original-entry-verification-failed');}
  const projected=new Map(existingLoadedChunks);
  // Projection ONLY. These values are CPU geometry descriptors, not buffers
  // and never passed into the actual live renderer's chunks map.
  for(const item of ready)projected.set(item.key,freeze({
    researchPreviewOnly:true,
    originalEntry:existingLoadedChunks.get(item.key),
    plannedOpaqueBytes:item.opaqueBytes,plannedWaterBytes:item.waterBytes
  }));
  return freeze({status:'cpu-preview-only',reason:'all-cpu-stages-validated',
    stageCount:ready.length,bytesStaged:bytes,
    projectedChunks:projected,stages:freeze(ready),
    wouldReplaceLoadedChunkCount:ready.length,
    survivingOriginalChunkCount:existingLoadedChunks.size,
    ...noPermission});
}
