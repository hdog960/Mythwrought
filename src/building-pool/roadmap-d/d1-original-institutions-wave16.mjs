export function buildWave16Original(p){
 const base=buildDistinctive4B(p),occupied=new Set(base.cells.map(c=>c.at.join(',')));
 const cells=[...base.cells];let count=0;
 const add=(x,y,z,role,asset,feature)=>{
  if(x<0||y<8||z<0||x>=base.bounds[0]||y>=base.bounds[1]||z>=base.bounds[2])throw Error('out-of-bounds extra source '+p.title);
  const at=[x,y,z].join(',');if(occupied.has(at))return;
  if(!occupied.has([x,y-1,z].join(',')))throw Error('unborne original source roof cell '+p.title+' '+at);
  cells.push({at:[x,y,z],role,asset,facing:'north',feature});occupied.add(at);count++;
 };
 // Graded original physical ridge columns; never overwrite immutable base roofs.
 for(const [axis,fixed,from,to,top] of p.ridges)for(let v=from;v<=to;v++){
  const x=axis==='x'?v:fixed,z=axis==='z'?v:fixed;
  const height=Math.max(9,top-Math.floor(Math.abs(v-Math.floor((from+to)/2))/6));
  for(let y=8;y<=height;y++)add(x,y,z,y===height?'trim':'roof','live:wood','graded-'+p.roof);
 }
 for(const [cx,cz,r,top] of p.towers)for(let y=8;y<=top;y++)for(let x=cx-r;x<=cx+r;x++)for(let z=cz-r;z<=cz+r;z++){
  if(Math.abs(x-cx)!==r&&Math.abs(z-cz)!==r)continue;
  add(x,y,z,y===top?'trim':'column',y===top?'live:crystal':'live:stone','tower-'+p.roof);
 }
 if(count<100)throw Error('missing real original elevated roof geometry '+p.title);
 const b=Object.freeze({...base,cells,provenance:{...base.provenance,lane:'roadmap-d',milestone:'D1-wave16',originalPlan:p.title,
  source:'Eight independently coordinate-authored original D0 vacant schools and research institutes',
  method:'original varied wings/round court skywell, supported pitched roof ridge course and freestanding tower source cells',
  originalBaseCellsIntact:true,originalElevatedCells:count,notFinalArt:true,liveIntegration:false}});
 validateBlueprint(b);return b;
}
